"""Generate regulus-code-mascot.svg from regulus-code-mascot.json and check the grids.

Run from any directory: python3 assets/design/build_mascot.py
With --check nothing is written: it fails if the SVG on disk is not what the JSON gives.
No dependencies. Colors come from palette.json by role, never from this file.
"""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "regulus-code-mascot.json"
TARGET = ROOT / "regulus-code-mascot.svg"

mascot = json.loads(SOURCE.read_text())
colors = json.loads((ROOT / "palette.json").read_text())["colors"]
roles = mascot["roles"]
EMPTY = mascot["empty"]
# What an eye cell is when a pose leaves it closed: the face shows through.
EYE = next(key for key, role in roles.items() if role["name"] == "eye")
FACE = next(key for key, role in roles.items() if role["name"] == "face")


def validate(name, grid):
    rows = grid["rows"]
    width = len(rows[0])
    for index, row in enumerate(rows):
        if len(row) != width:
            raise ValueError(f"{name}: row {index} is {len(row)} wide, the grid is {width}")
        if row != row[::-1]:
            raise ValueError(f"{name}: row {index} is not symmetric: {row}")
        for cell in row:
            if cell != EMPTY and cell not in roles:
                raise ValueError(f"{name}: row {index} has an unknown role `{cell}`")
    if "idle" not in grid["poses"]:
        raise ValueError(f"{name}: no `idle` pose")
    idle = sorted(map(tuple, grid["poses"]["idle"]))
    drawn = sorted((r, c) for r, row in enumerate(rows) for c, cell in enumerate(row) if cell == EYE)
    if idle != drawn:
        raise ValueError(f"{name}: the rows draw the eyes at {drawn}, the idle pose says {idle}")
    for pose, cells in grid["poses"].items():
        for r, c in cells:
            if not (0 <= r < len(rows) and 0 <= c < width) or rows[r][c] not in (FACE, EYE):
                raise ValueError(f"{name}: pose `{pose}` puts an eye outside the face at {r},{c}")


def posed(grid, pose):
    """The grid's rows with the eyes where `pose` puts them."""
    eyes = {tuple(cell) for cell in grid["poses"][pose]}
    return ["".join(EYE if (r, c) in eyes else FACE if cell == EYE else cell for c, cell in enumerate(row))
            for r, row in enumerate(grid["rows"])]


def runs(row):
    """Horizontal runs of one role: (start, length, role)."""
    start = 0
    for index in range(1, len(row) + 1):
        if index == len(row) or row[index] != row[start]:
            if row[start] != EMPTY:
                yield start, index - start, row[start]
            start = index


def svg(grid):
    rows = posed(grid, "idle")
    width, height = len(rows[0]), len(rows)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width * 16}" '
           f'height="{height * 16}" shape-rendering="crispEdges" role="img" aria-labelledby="title desc">',
           f'  <title id="title">{mascot["name"]}</title>',
           '  <desc id="desc">A small lion seen from the front, on a pixel grid: a mane with star points, '
           'a heart-shaped face and a star on its forehead.</desc>',
           "  <!-- Generated by build_mascot.py from regulus-code-mascot.json. Do not edit by hand. -->",
           "  <style>"]
    for role in roles.values():
        out.append(f"    .{role['name']} {{ fill: var(--rg-color-{role['token']}, {colors[role['token']]}); }}")
    out.append("  </style>")
    for y, row in enumerate(rows):
        for x, length, key in runs(row):
            out.append(f'  <rect class="{roles[key]["name"]}" x="{x}" y="{y}" width="{length}" height="1" />')
    out.append("</svg>")
    return "\n".join(out) + "\n"


for grid_name, grid in mascot["grids"].items():
    validate(grid_name, grid)
text = svg(mascot["grids"]["full"])
if "--check" in sys.argv[1:]:
    if not TARGET.exists() or TARGET.read_text() != text:
        sys.exit(f"{TARGET.name} is not what {SOURCE.name} gives: run build_mascot.py")
    print(f"{TARGET.name} matches {SOURCE.name}; {len(mascot['grids'])} grids are valid.")
else:
    TARGET.write_text(text)
    print(f"Generated {TARGET.name} from {SOURCE.name}; {len(mascot['grids'])} grids are valid.")
